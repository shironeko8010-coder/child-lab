  function px(lon) { return (lon + 180) * 2; }
  function py(lat) { return (90 - lat) * 2; }
  function polyD(arr) {
    var o = '';
    for (var i = 0; i < arr.length; i += 2) o += (i ? 'L' : 'M') + f2(px(arr[i])) + ',' + f2(py(arr[i + 1]));
    return o + 'Z';
  }
  function shapeD(list) { return list.map(polyD).join(''); }
  // 形の外枠（地図の座標）
  function bboxOf(list) {
    var b = { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity };
    list.forEach(function (arr) {
      for (var i = 0; i < arr.length; i += 2) {
        var x = px(arr[i]), y = py(arr[i + 1]);
        if (x < b.x1) b.x1 = x; if (x > b.x2) b.x2 = x;
        if (y < b.y1) b.y1 = y; if (y > b.y2) b.y2 = y;
      }
    });
    return b;
  }

