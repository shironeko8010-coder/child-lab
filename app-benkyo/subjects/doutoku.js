  var SCENES = RAW.map(function (r) {
    return {
      id: r[0], name: r[1], kind: r[2], text: r[3], pic: r[4],
      choices: r[5].map(function (c) { return { text: c[0], good: c[1] == null ? null : !!c[1], reply: c[2] }; }),
      end: r[6] || (r[2] === 'think' ? THINK_END : ''),
      quiet: !!r[7]       // よろこぶ音・星の音を出さない（ねこと おわかれ）
    };
  });
  var BY_ID = {}, BY_NAME = {};
  SCENES.forEach(function (s) { BY_ID[s.id] = s; BY_NAME[s.name] = s; });

  /* ---------- ふりがなの記法 {漢字|よみ} ---------- */
  // 画面用：[{t:'文字'}, {t:'国', y:'くに'}, ...]
  function segments(text) {
    var out = [], re = /\{([^|{}]+)\|([^|{}]+)\}/g, last = 0, m;
    text = String(text || '');
    while ((m = re.exec(text))) {
      if (m.index > last) out.push({ t: text.slice(last, m.index) });
      out.push({ t: m[1], y: m[2] });
      last = re.lastIndex;
    }
    if (last < text.length) out.push({ t: text.slice(last) });
    return out;
  }
  function yomi(text) { return String(text || '').replace(/\{([^|{}]+)\|([^|{}]+)\}/g, '$2'); }      // 声用
  function plain(text) { return String(text || '').replace(/\{([^|{}]+)\|([^|{}]+)\}/g, '$1'); }     // ふりがな なし

  /* ---------- 記録から進み具合 ---------- */
  // seen: 場面ごとに出た回数、missed: 1回目で望ましい答えを選ばなかった回数（えらぶ もんだいだけ）
  function progressFromLogs(logs) {
    var seen = {}, missed = {};
    (logs || []).forEach(function (e) {
      if (!e || (e.area !== AREA && e.area !== AREA_THINK)) return;
      var s = BY_NAME[e.itemId];
      if (!s) return;
      seen[s.id] = (seen[s.id] || 0) + 1;
      if (e.area === AREA && !e.correct) missed[s.id] = (missed[s.id] || 0) + 1;
    });
    return { seen: seen, missed: missed };
  }

  /* ---------- 出題（1回＝10もん） ---------- */
  function shuffle(a, rng) {
    a = a.slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(rng() * (i + 1));
      if (j > i) j = i;
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }
  // まだ出ていない → 前に1回目でえらべなかった（多い順） → そのほか（出た回数の少ない順）。同じ段の中はばらばら
  function rank(list, prog, rng) {
    var seen = prog.seen || {}, missed = prog.missed || {};
    var mixed = shuffle(list, rng);
    function tier(s) { return !seen[s.id] ? 0 : missed[s.id] ? 1 : 2; }
    var order = {};
    mixed.forEach(function (s, i) { order[s.id] = i; });
    return mixed.slice().sort(function (a, b) {
      var ta = tier(a), tb = tier(b);
      if (ta !== tb) return ta - tb;
      if (ta === 1 && missed[a.id] !== missed[b.id]) return missed[b.id] - missed[a.id];
      if (ta === 2 && seen[a.id] !== seen[b.id]) return seen[a.id] - seen[b.id];
      return order[a.id] - order[b.id];
    });
  }
  function pickRound(prog, rng) {
    prog = prog || {};
    rng = rng || Math.random;
    var choice = rank(SCENES.filter(function (s) { return s.kind === 'choice'; }), prog, rng);
    var think = rank(SCENES.filter(function (s) { return s.kind === 'think'; }), prog, rng);
    var out = [], ci = 0, ti = 0;
    for (var i = 0; i < ROUND_SIZE; i++) {
      if (THINK_SLOTS.indexOf(i) >= 0 && ti < think.length) out.push(think[ti++].id);
      else out.push(choice[ci++].id);
    }
    return out;
  }

  /* ---------- 1問の流れ ---------- */
  // 選択肢のならびを入れかえる（もとの番号 idx を持たせる）
  function arrange(scene, rng) {
    rng = rng || Math.random;
    return shuffle(scene.choices.map(function (c, i) {
      return { idx: i, text: c.text, good: c.good, reply: c.reply };
    }), rng);
  }
  function newAttempt() { return { tried: [], done: false, firstTry: null }; }
  // idx はもとの番号。返り値 kind: 'good'（ほめる）| 'retry'（理由→もう一度）| 'think'（受けとめる）| 'ignore'
  function choose(attempt, scene, idx) {
    var c = scene && scene.choices[idx];
    if (!attempt || attempt.done || !c || attempt.tried.indexOf(idx) >= 0) return { kind: 'ignore' };
    var first = attempt.tried.length === 0;
    attempt.tried.push(idx);
    if (scene.kind === 'think') {
      attempt.done = true;
      attempt.firstTry = true;
      return { kind: 'think', reply: c.reply, end: scene.end, firstTry: true };
    }
    if (c.good) {
      attempt.done = true;
      attempt.firstTry = first;
      return { kind: 'good', reply: c.reply, firstTry: first };
    }
    return { kind: 'retry', reply: c.reply, firstTry: false };
  }
  // 記録の1件（えらぶ もんだいは done になってから。かんがえる もんだいは いつも true）
  function logEntry(scene, attempt) {
    if (scene.kind === 'think') return { area: AREA_THINK, itemId: scene.name, correct: true, level: 1 };
    return { area: AREA, itemId: scene.name, correct: !!(attempt && attempt.firstTry), level: 1 };
  }

  /* ---------- 声 ---------- */
  function speakText(scene) {
    return yomi(scene.text) + (scene.kind === 'choice' ? ' ' + ASK : '');
  }
  function replyText(scene, result) {
    if (!result) return '';
    if (result.kind === 'retry') return yomi(result.reply) + ' ' + RETRY;
    if (result.kind === 'think') return yomi(result.reply) + ' ' + yomi(result.end || THINK_END);
    return yomi(result.reply);
  }
  // 長い文は、文ごとに分けて読む（voice.speak は1回あたり最大6秒で終わるため）
  function sentences(text) {
    return String(text || '').replace(/([。！？])\s*/g, '$1\n').split('\n')
      .map(function (s) { return s.replace(/^\s+|\s+$/g, ''); })
      .filter(function (s) { return s.length > 0; });
  }

